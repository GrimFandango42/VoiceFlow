def _write_stamp(path: Path, commit: str, *, dirty: bool = False) -> Path:
    # The build writes this with PowerShell's UTF8 encoding (BOM included).
    path.write_text(
        "﻿# Generated by scripts/setup/build_windows_exe.ps1. Do not edit, do not commit.\n"
        f'VERSION = "3.2.1"\nCOMMIT = "{commit}"\nBUILT_AT = "11-08 15:40"\nDIRTY = {dirty}\n',
        encoding="utf-8",
    )
    return path


